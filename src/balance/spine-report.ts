// Prints the spine: solved values, the first-run decomposition, the pace sweep against the
// 2-3x cap, and the levers that move it. A script that prints, not a test: `pnpm spine`.
// `--write` regenerates src/game/spine-solved.ts from a fresh solve; `--check` exits nonzero
// when the committed values differ from one, a derivation guard lint-staged runs.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
  ANCHORS,
  NO_UPGRADES,
  deriveSpine,
  rateOf,
  referencePersona,
  takeHome,
  type Anchors,
  type Persona,
  type Spine,
} from '../game/spine'
import { SPINE_SOLVED } from '../game/spine-solved'
import {
  finaleRatio,
  solveAtStep,
  solveSpine,
  walk,
  type Solved,
} from './spine-walk'

const SOLVED_PATH = fileURLToPath(
  new URL('../game/spine-solved.ts', import.meta.url)
)

const MILESTONES = ['tier 2', 'tier 3', 'tier 4', 'tier 5', 'finale']

function table(headers: string[], rows: (string | number)[][]): string {
  const line = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`
  return [
    line(headers),
    line(headers.map(() => '---')),
    ...rows.map(line),
  ].join('\n')
}

const f = (n: number, digits = 1) =>
  Number.isFinite(n) ? n.toFixed(digits) : '—'

function sweepGaps(spine: Spine): number[] {
  const { slowestGap, fastestGap } = spine.anchors.pace
  const steps = 6
  return Array.from(
    { length: steps + 1 },
    (_, i) => fastestGap * (slowestGap / fastestGap) ** (i / steps)
  )
}

function milestones(
  spine: Spine,
  prices: number[],
  persona: Persona,
  gap: number
): number[] {
  const r = walk(spine, prices, persona, 60 / gap)
  return [...r.unlockMinutes.slice(2), r.finaleMinutes]
}

/** Six significant digits keep the generated values stable across re-solves. */
const rounded = (solved: Solved): Solved => {
  const n = (x: number) => Number(x.toPrecision(6))
  return {
    comboExponentStep: n(solved.comboExponentStep),
    tierPrices: solved.tierPrices.map(n),
    timedLimits: solved.timedLimits.map(n),
  }
}

const sameSolve = (a: Solved, b: Solved) =>
  JSON.stringify(rounded(a)) === JSON.stringify(rounded(b))

/** The generated module's text, before oxfmt. */
function solvedModule(solved: Solved & { ratio: number }): string {
  const { comboExponentStep, tierPrices, timedLimits } = rounded(solved)
  return [
    '// Generated by `pnpm spine --write` from the anchors in spine.ts; `pnpm spine --check`',
    '// guards it. Do not edit.',
    '',
    'export const SPINE_SOLVED = {',
    `  // Reference persona's finale time, slowest pace over fastest: ${solved.ratio.toFixed(2)}x.`,
    `  comboExponentStep: ${comboExponentStep},`,
    '  // Index = tier; tier 1 is free.',
    `  tierPrices: [${tierPrices.join(', ')}],`,
    '  // Seconds, index = tier − 1.',
    `  timedLimits: [${timedLimits.join(', ')}],`,
    '}',
    '',
  ].join('\n')
}

function firstRunSplit(spine: Spine, persona: Persona) {
  const run = (gap: number) =>
    takeHome(spine, {
      pace: 60 / gap,
      shipQuality: persona.shipQuality,
      tier: 1,
      upgrades: NO_UPGRADES,
    })
  const slow = run(spine.anchors.pace.slowestGap)
  const fast = run(spine.anchors.pace.fastestGap)
  return {
    slow,
    fast,
    durationRatio: slow.duration / fast.duration,
    comboRatio: fast.currency / slow.currency,
    rateRatio: rateOf(fast) / rateOf(slow),
  }
}

function report(fresh: Solved & { ratio: number }): void {
  const spine = deriveSpine()
  const prices = SPINE_SOLVED.tierPrices
  const a = spine.anchors
  const out: string[] = []

  out.push('# Heaviest spine\n')
  out.push(
    sameSolve(SPINE_SOLVED, fresh)
      ? 'spine-solved.ts matches a fresh solve.\n'
      : '**spine-solved.ts is stale: run `pnpm spine --write`.** The tables below read it as committed.\n'
  )
  out.push(
    `Reference gap ${f(spine.referenceGap, 2)} s (pace ${f(60 / spine.referenceGap)}/min). ` +
      `Base combo window ${f(spine.baseWindow, 2)} s (today 3 s). ` +
      `Combo exponent ${a.comboBaseExponent} + ${f(spine.comboExponentStep, 4)} per level, ` +
      `landing the tidy finale ratio at ${f(fresh.ratio, 2)}× under the ${a.capTarget}× cap.\n`
  )
  const referenceWalk = walk(
    spine,
    prices,
    referencePersona(a),
    60 / spine.referenceGap
  )
  out.push('## Boards\n')
  out.push(
    table(
      [
        'tier',
        'scopes',
        'problems',
        'weight',
        'richness',
        'ref run (min)',
        'timed limit (min)',
        'unlock price',
        'scheduled (min)',
        'walked (min)',
      ],
      a.tiers.map((t, i) => {
        const ref = takeHome(spine, {
          pace: 60 / spine.referenceGap,
          shipQuality: referencePersona(a).shipQuality,
          tier: i + 1,
          upgrades: NO_UPGRADES,
        })
        const b = spine.boards[i]!
        return [
          `${i + 1} ${t.id}`,
          b.scopes,
          b.problems,
          Math.round(b.weight),
          f(b.richness, 2),
          f(ref.duration / 60, 2),
          f(spine.timedLimits[i]! / 60, 2),
          i === 0 ? '—' : Math.round(prices[i + 1]!),
          a.unlockMinutes[i + 1]!,
          f(referenceWalk.unlockMinutes[i + 1]!),
        ]
      })
    )
  )

  out.push(
    '\n## Auto-resolve ladder: slowest pace, fully stable board, share of left-behind conflicts cleared\n'
  )
  out.push(autoResolveRows(spine))

  out.push('\n## First run, tier 1, no upgrades: slowest vs fastest pace\n')
  out.push(
    table(
      [
        'persona',
        'slow min',
        'fast min',
        'slow d̄',
        'fast d̄',
        'duration ×',
        'combo ×',
        'rate ×',
      ],
      a.personas.map((p) => {
        const s = firstRunSplit(spine, p)
        return [
          p.id,
          f(s.slow.duration / 60, 2),
          f(s.fast.duration / 60, 2),
          f(s.slow.comboDepth, 2),
          f(s.fast.comboDepth, 2),
          f(s.durationRatio, 2),
          f(s.comboRatio, 2),
          f(s.rateRatio, 2),
        ]
      })
    )
  )

  const gaps = sweepGaps(spine)
  for (const p of a.personas) {
    out.push(
      `\n## Sweep: ${p.id} (q* = ${p.shipQuality}), minutes to each milestone\n`
    )
    const rows = gaps.map((g) => [
      `${f(g, 2)} s`,
      ...milestones(spine, prices, p, g).map((m) => f(m)),
    ])
    const fast = milestones(spine, prices, p, a.pace.fastestGap)
    const slow = milestones(spine, prices, p, a.pace.slowestGap)
    const ratios = slow.map((s, i) => s / fast[i]!)
    rows.push(['slow ÷ fast', ...ratios.map((r) => f(r, 2))])
    out.push(table(['gap', ...MILESTONES], rows))
    const drift = ratios[ratios.length - 1]! / ratios[0]!
    out.push(
      `\nShape: ${drift > 1.1 ? 'spread' : drift < 0.9 ? 'convergence' : 'parallel'} (finale ratio ÷ tier-2 ratio = ${f(drift, 2)}).`
    )
    const end = walk(spine, prices, p, 60 / a.pace.fastestGap)
    const endSlow = walk(spine, prices, p, 60 / a.pace.slowestGap)
    out.push(
      `\nUpgrades at the finale, fastest: ${JSON.stringify(end.upgrades)}; slowest: ${JSON.stringify(endSlow.upgrades)}`
    )
  }

  out.push('\n## Lower tiers late: tidy persona, upgrades as at its finale\n')
  out.push(lowerTierRows(spine, prices))

  out.push(
    `\n## Levers: tidy persona, Δe re-solved onto ${a.capTarget}×; "Δe = 0 ×" is the finale ratio with no combo growth\n`
  )
  out.push(leverRows())

  console.log(out.join('\n'))
}

/** A lower tier's run length and pay per minute against tier 5, so a short session's worth shows. */
function lowerTierRows(spine: Spine, prices: number[]): string {
  const p = referencePersona(spine.anchors)
  const rows: (string | number)[][] = []
  const ends = [
    spine.anchors.pace.fastestGap,
    spine.anchors.pace.slowestGap,
  ].map((gap) => ({
    gap,
    upgrades: walk(spine, prices, p, 60 / gap).upgrades,
  }))
  for (let tier = 1; tier <= 5; tier++) {
    const row: (string | number)[] = [tier]
    for (const { gap, upgrades } of ends) {
      const run = (t: number) =>
        takeHome(spine, {
          pace: 60 / gap,
          shipQuality: p.shipQuality,
          tier: t,
          upgrades,
          unlockedTier: 5,
        })
      row.push(
        f(run(tier).duration / 60, 2),
        f(rateOf(run(tier)) / rateOf(run(5)), 2)
      )
    }
    rows.push(row)
  }
  return table(
    [
      'tier',
      'fast run (min)',
      'fast pay ÷ tier 5',
      'slow run (min)',
      'slow pay ÷ tier 5',
    ],
    rows
  )
}

function autoResolveRows(spine: Spine): string {
  const slow = 60 / spine.anchors.pace.slowestGap
  const cleared = (tier: number, level: number) => {
    const run = takeHome(spine, {
      pace: slow,
      shipQuality: 1,
      tier,
      upgrades: { ...NO_UPGRADES, autoResolve: level },
    })
    const conflicts =
      spine.boards[tier - 1]!.problems * spine.anchors.conflictShare
    return run.autoResolved / conflicts
  }
  const rows = spine.autoResolveIntervals
    .slice(1)
    .map((interval, i) => [
      i + 1,
      f(interval, 2),
      ...[1, 2, 3, 4, 5].map((tier) => f(cleared(tier, i + 1), 2)),
    ])
  return table(
    ['level', 'interval (s)', ...[1, 2, 3, 4, 5].map((t) => `tier ${t} share`)],
    rows
  )
}

/** Each lever changes anchors, and the whole spine re-solves from them. */
function leverRows(): string {
  const levers: [string, Anchors][] = [
    ['base', ANCHORS],
    [
      'fastest gap 3 s',
      { ...ANCHORS, pace: { ...ANCHORS.pace, fastestGap: 3 } },
    ],
    ['transition 8 s', { ...ANCHORS, transitionSeconds: 8 }],
    ['run fixed 60 s', { ...ANCHORS, runFixedSeconds: 60 }],
    ['overhead ∝ gap (β = 1)', { ...ANCHORS, overheadPaceExponent: 1 }],
    ['gap CV 0.25 (k = 16)', { ...ANCHORS, gapShape: 16 }],
    ['no timed reward', { ...ANCHORS, timedReward: 0 }],
    [
      'auto-resolve level 1 clears all',
      { ...ANCHORS, autoResolveFirstShare: 1 },
    ],
    ['combo base exponent 0', { ...ANCHORS, comboBaseExponent: 0 }],
    ['cap target 2.5×', { ...ANCHORS, capTarget: 2.5 }],
  ]
  const rows = levers.map(([name, anchors]) => {
    const p = referencePersona(anchors)
    const still = solveAtStep(anchors, 0)
    const floor = finaleRatio(deriveSpine(anchors, still), still.tierPrices, p)
    const split = firstRunSplit(deriveSpine(anchors, still), p)
    let step = '—'
    let solved = 'fails'
    try {
      const s = solveSpine(anchors)
      step = f(s.comboExponentStep, 4)
      solved = f(s.ratio, 2)
    } catch {
      // The solve throws when no Δe reaches the target; the row shows it.
    }
    return [name, f(split.durationRatio, 2), f(floor, 2), step, solved]
  })
  return table(
    ['lever', 'first-run duration ×', 'Δe = 0 ×', 'solved Δe', 'finale ×'],
    rows
  )
}

const mode = process.argv.includes('--write')
  ? 'write'
  : process.argv.includes('--check')
    ? 'check'
    : 'report'
const fresh = solveSpine(ANCHORS)
if (mode === 'write') {
  writeFileSync(SOLVED_PATH, solvedModule(fresh))
  execFileSync('oxfmt', [SOLVED_PATH], { stdio: 'inherit' })
  console.log(`wrote ${SOLVED_PATH}`)
} else if (mode === 'check') {
  if (!sameSolve(SPINE_SOLVED, fresh)) {
    console.error(
      'src/game/spine-solved.ts differs from a fresh solve: run `pnpm spine --write`'
    )
    process.exit(1)
  }
} else {
  report(fresh)
}

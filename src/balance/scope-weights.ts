// Samples the mean raw weight of a scope by map tier and scope depth, by running the
// cascade's own rolls (formulas.ts) over the registry's pools. A scope's weight is its
// deps, their sub-deps and collected fragments, golden packages included; a top-level
// scope adds its owner. The guaranteed duplicate pairs are drawn from the general pool,
// as the rest of a scope is. board.ts divides the spine's board weight by these.

import { chance, seedRNG } from '@open-loop/engine'
import { CASCADE_CRIT_CHANCE, FRAGMENT_WEIGHT } from '../game/config'
import {
  carriesFragment,
  getIdentitySize,
  rollGolden,
  rollScopeDepCount,
  rollSubDepCount,
  spawnedSize,
} from '../game/formulas'
import {
  pickDirectInstallIdentity,
  pickRandomIdentity,
  type PackageIdentity,
} from '../game/registry'
import type { ScopeWeights } from '../game/scope-weights'

const SAMPLES = 20000
const SEED = 1

function spawn(
  identity: PackageIdentity,
  depth: number,
  tier: number,
  min: number
) {
  const golden = rollGolden(depth, tier)
  return (
    spawnedSize(getIdentitySize(identity, min), depth, golden) +
    (carriesFragment(identity, golden) ? FRAGMENT_WEIGHT : 0)
  )
}

function scopeWeight(
  owner: PackageIdentity,
  depth: number,
  tier: number
): number {
  const count = rollScopeDepCount(owner, depth, chance(CASCADE_CRIT_CHANCE))
  let weight = 0
  for (let i = 0; i < count; i++) {
    weight += spawn(pickRandomIdentity(), depth + 1, tier, 10)
    for (let j = rollSubDepCount(); j > 0; j--) {
      weight += spawn(pickRandomIdentity(), depth + 2, tier, 5)
    }
  }
  return weight
}

function mean(sample: () => number): number {
  let sum = 0
  for (let i = 0; i < SAMPLES; i++) sum += sample()
  return sum / SAMPLES
}

/** The table, from a fixed seed so a re-run reproduces it. */
export function sampleScopeWeights(): ScopeWeights {
  seedRNG(SEED)
  const tiers = [1, 2, 3, 4, 5]
  return {
    topLevel: tiers.map((tier) =>
      mean(() => {
        const owner = pickDirectInstallIdentity(tier, new Set())
        return getIdentitySize(owner) + scopeWeight(owner, 1, tier)
      })
    ),
    nested: tiers.map((tier) =>
      Array.from({ length: tier - 1 }, (_, i) =>
        mean(() => scopeWeight(pickRandomIdentity(), i + 2, tier))
      )
    ),
  }
}

/** Five significant digits keep the generated values stable. */
export function roundedScopeWeights(w: ScopeWeights): ScopeWeights {
  const n = (x: number) => Number(x.toPrecision(5))
  return {
    topLevel: w.topLevel.map(n),
    nested: w.nested.map((row) => row.map(n)),
  }
}

/** The generated module's text, before oxfmt. */
export function scopeWeightsModule(w: ScopeWeights): string {
  const { topLevel, nested } = roundedScopeWeights(w)
  return [
    '// Generated by `pnpm spine --write`: src/balance/scope-weights.ts samples the',
    `// cascade's rolls, ${SAMPLES} scopes per cell, seed ${SEED}. \`pnpm spine --check\` guards it. Do not edit.`,
    '',
    'export interface ScopeWeights {',
    '  /** Index = tier − 1: a top-level scope, its owner included. */',
    '  topLevel: number[]',
    '  /** Index = tier − 1, then scope depth − 2. */',
    '  nested: number[][]',
    '}',
    '',
    'export const SCOPE_WEIGHTS: ScopeWeights = {',
    `  topLevel: [${topLevel.join(', ')}],`,
    `  nested: [${nested.map((row) => `[${row.join(', ')}]`).join(', ')}],`,
    '}',
    '',
  ].join('\n')
}

// Samples what a scope holds on average, by map tier and scope depth, by running the
// cascade's own rolls (formulas.ts) over the registry's pools: its raw weight, and its
// problems, duplicates and conflicts. A scope's weight is its deps, their sub-deps and
// collected fragments, golden packages included; a top-level scope adds its owner. board.ts
// divides the spine's board weight by the weights; the spine reads the problems.

import { chance, seedRNG } from '@open-loop/engine'
import {
  CASCADE_CRIT_CHANCE,
  FRAGMENT_WEIGHT,
  TIER_BOARDS,
} from '../game/config'
import {
  carriesFragment,
  getIdentitySize,
  rollGolden,
  rollScopeDepCount,
  rollScopeDeps,
  rollSubDepCount,
  spawnedSize,
} from '../game/formulas'
import {
  areIncompatible,
  pickDirectInstallIdentity,
  pickRandomIdentity,
  type PackageIdentity,
} from '../game/registry'
import type { ScopeMean, ScopeMeans } from '../game/scope-means'

const SAMPLES = 20000
const SEED = 1

function spawn(
  identity: PackageIdentity,
  depth: number,
  tier: number,
  min: number
) {
  const golden = rollGolden(depth, tier)
  return (
    spawnedSize(getIdentitySize(identity, min), depth, golden) +
    (carriesFragment(identity, golden) ? FRAGMENT_WEIGHT : 0)
  )
}

/** One scope's cascade: deps in spawn order, then the sub-deps they grow. */
function sampleScope(
  owner: PackageIdentity,
  depth: number,
  tier: number
): ScopeMean {
  const count = rollScopeDepCount(owner, depth, chance(CASCADE_CRIT_CHANCE))
  const spawned: PackageIdentity[] = []
  let weight = 0
  const subDeps: PackageIdentity[] = []
  for (const dep of rollScopeDeps(
    count,
    TIER_BOARDS[tier - 1]!.conflictPairs
  )) {
    spawned.push(dep)
    weight += spawn(dep, depth + 1, tier, 10)
    for (let j = rollSubDepCount(); j > 0; j--) {
      const sub = pickRandomIdentity()
      subDeps.push(sub)
      weight += spawn(sub, depth + 2, tier, 5)
    }
  }
  spawned.push(...subDeps)

  // A package conflicts when it spawns beside one it is incompatible with; a duplicate is
  // each copy past an identity's first.
  let conflicts = 0
  const seen = new Map<string, number>()
  for (const identity of spawned) {
    for (const name of seen.keys()) {
      if (areIncompatible(identity.name, name)) {
        conflicts++
        break
      }
    }
    seen.set(identity.name, (seen.get(identity.name) ?? 0) + 1)
  }
  let duplicates = 0
  for (const n of seen.values()) duplicates += n - 1
  return { weight, duplicates, conflicts }
}

function mean(sample: () => ScopeMean): ScopeMean {
  const sum = { weight: 0, duplicates: 0, conflicts: 0 }
  for (let i = 0; i < SAMPLES; i++) {
    const s = sample()
    sum.weight += s.weight
    sum.duplicates += s.duplicates
    sum.conflicts += s.conflicts
  }
  return {
    weight: sum.weight / SAMPLES,
    duplicates: sum.duplicates / SAMPLES,
    conflicts: sum.conflicts / SAMPLES,
  }
}

/** The table, from a fixed seed so a re-run reproduces it. */
export function sampleScopeMeans(): ScopeMeans {
  seedRNG(SEED)
  const tiers = [1, 2, 3, 4, 5]
  return {
    topLevel: tiers.map((tier) =>
      mean(() => {
        const owner = pickDirectInstallIdentity(tier, new Set())
        const scope = sampleScope(owner, 1, tier)
        return { ...scope, weight: scope.weight + getIdentitySize(owner) }
      })
    ),
    nested: tiers.map((tier) =>
      Array.from({ length: tier - 1 }, (_, i) =>
        mean(() => sampleScope(pickRandomIdentity(), i + 2, tier))
      )
    ),
  }
}

/** Five significant digits keep the generated values stable. */
export function roundedScopeMeans(m: ScopeMeans): ScopeMeans {
  const n = (x: number) => Number(x.toPrecision(5))
  const cell = (c: ScopeMean): ScopeMean => ({
    weight: n(c.weight),
    duplicates: n(c.duplicates),
    conflicts: n(c.conflicts),
  })
  return {
    topLevel: m.topLevel.map(cell),
    nested: m.nested.map((row) => row.map(cell)),
  }
}

/** The generated module's text, before oxfmt. */
export function scopeMeansModule(m: ScopeMeans): string {
  const { topLevel, nested } = roundedScopeMeans(m)
  const cell = (c: ScopeMean) =>
    `{ weight: ${c.weight}, duplicates: ${c.duplicates}, conflicts: ${c.conflicts} }`
  return [
    '// Generated by `pnpm spine --write`: src/balance/scope-means.ts samples the',
    `// cascade's rolls, ${SAMPLES} scopes per cell, seed ${SEED}. \`pnpm spine --check\` guards it. Do not edit.`,
    '',
    'export interface ScopeMean {',
    '  /** Raw weight, before the board scale. */',
    '  weight: number',
    '  duplicates: number',
    '  conflicts: number',
    '}',
    '',
    'export interface ScopeMeans {',
    '  /** Index = tier − 1: a top-level scope, its owner included. */',
    '  topLevel: ScopeMean[]',
    '  /** Index = tier − 1, then scope depth − 2. */',
    '  nested: ScopeMean[][]',
    '}',
    '',
    'export const SCOPE_MEANS: ScopeMeans = {',
    `  topLevel: [${topLevel.map(cell).join(', ')}],`,
    `  nested: [${nested.map((row) => `[${row.map(cell).join(', ')}]`).join(', ')}],`,
    '}',
    '',
  ].join('\n')
}
